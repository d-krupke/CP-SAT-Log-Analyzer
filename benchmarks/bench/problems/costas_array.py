"""Costas arrays (CSPLib prob076) as a pure satisfaction problem.

Created 2026-09-06 for the CP-SAT log collection. Purpose in the corpus: a
permutation problem whose only constraints are ``AddAllDifferent`` -- one over
the permutation itself and one over every row of the difference triangle
(``n`` AllDifferent constraints over linear expressions). Satisfiable for every
``n`` in the range used here, but the search effort grows steeply, so the logs
show pure feasibility search that goes from "instant" (n=10) to "minutes"
(n>=17) without any objective.

Instances are generated (no download, ``Instance.path is None``); ``meta``
carries ``n``.
"""

from __future__ import annotations

from pathlib import Path

from ortools.sat.python import cp_model

from ..base import Instance, Problem

SIZES = tuple(range(10, 19))


def download(data_dir: Path) -> None:
    """Nothing to download: instances are generated from ``meta['n']``."""


def instances(data_dir: Path) -> list[Instance]:
    return [
        Instance(
            name=f"n{n:02d}",
            meta={"n": n, "num_differences": n * (n - 1) // 2},
        )
        for n in sorted(SIZES)
    ]


def build(instance: Instance) -> cp_model.CpModel:
    """``a`` is a permutation of ``1..n``; every row of its difference triangle
    ``d[k][i] = a[i+k] - a[i]`` must itself have pairwise distinct entries.

    Encoded with ``AddAllDifferent`` on ``a`` and one ``AddAllDifferent`` per
    row ``k``. The differences are kept as explicit variables (with 0 removed
    from their domain) so the log shows the difference triangle as a real part
    of the model rather than as inlined linear expressions.
    """
    n = instance.meta["n"]
    model = cp_model.CpModel()
    a = [model.new_int_var(1, n, f"a{i}") for i in range(n)]
    model.add_all_different(a)

    diffs: list[list[cp_model.IntVar]] = []
    for k in range(1, n):
        row = []
        for i in range(n - k):
            d = model.new_int_var_from_domain(
                cp_model.Domain.from_intervals([[-(n - 1), -1], [1, n - 1]]), f"d{k}_{i}"
            )
            model.add(d == a[i + k] - a[i])
            row.append(d)
        model.add_all_different(row)
        diffs.append(row)

    # Redundant constraint from the literature: the difference triangle is
    # generated by its first row (d[k][i] = d[k-1][i] + d[1][i+k-1]).
    for k in range(2, n):
        for i in range(n - k):
            model.add(diffs[k - 1][i] == diffs[k - 2][i] + diffs[0][i + k - 1])

    # Symmetry breaking: a Costas array stays one when reversed / complemented.
    model.add(a[0] < a[n - 1])
    return model


PROBLEM = Problem(
    name="costas_array",
    description="Costas array (CSPLib prob076) n=10..18, AllDifferent on every row of the difference triangle",
    download=download,
    instances=instances,
    build=build,
    source="https://www.csplib.org/Problems/prob076/",
)
